    @classmethod
    def get_profile(cls, profile_id: str) -> Optional[RenderProfile]:
        """Retrieves profile by ID."""
        return cls._PROFILES.get(profile_id)

    @classmethod
    def list_profiles(cls, category: Optional[ProfileCategory] = None) -> List[RenderProfile]:
        """Lists available profiles, optionally filtered by category."""
        if category:
            return [p for p in cls._PROFILES.values() if p.category == category]
        return list(cls._PROFILES.values())

    @classmethod
    def register_custom_profile(cls, profile: RenderProfile) -> None:
        """Registers a user-defined export profile."""
        cls._PROFILES[profile.profile_id] = profile

